import { expect, test } from '@playwright/test'

test('保存短文、追溯来源、维护个人 Wiki，并找回旧内容', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '让收藏，成为知识。' })).toBeVisible()
  await page.getByRole('button', { name: '记录内容', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '随手记', exact: true }).click()
  await dialog.getByLabel('标题').fill('Rerank 浏览器验收记录')
  await dialog.getByLabel('此刻的想法').fill('Rerank 在检索后对候选结果重新排序。保留面试复盘中的具体问题。')
  await dialog.getByRole('button', { name: '保存到知识库' }).click()
  await expect(page).toHaveURL(/\/records\//)
  await expect(page.getByRole('heading', { name: 'Rerank 浏览器验收记录' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '内容概览' })).toBeVisible({ timeout: 15000 })
  await page.getByRole('button', { name: '查看来源', exact: true }).first().click()
  await expect(page.locator('.source-card').first()).toContainText('Rerank 在检索后')
  await page.getByRole('link', { name: '知识 Wiki', exact: true }).click()
  await page.locator('.wiki-card').filter({ hasText: 'Rerank' }).first().click()
  await expect(page.getByRole('heading', { name: 'Rerank', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByLabel('个人笔记 Markdown').fill('这是我自己的理解，不应被自动整理覆盖。')
  await page.getByRole('button', { name: '保存笔记', exact: true }).click()
  await expect(page.locator('.personal-section')).toContainText('这是我自己的理解')
  await page.getByRole('button', { name: /v1 · 自动整理/ }).click()
  await expect(page.getByRole('heading', { name: '查看历史 · 第 1 版' })).toBeVisible()
  await page.getByRole('button', { name: '关闭历史版本' }).click()
  await page.getByLabel('搜索知识库').fill('Rerank')
  await page.getByLabel('搜索知识库').press('Enter')
  await expect(page.locator('.search-result').first()).toContainText('Rerank')
  await expect(page.locator('body')).not.toContainText('无法连接服务')
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: `../data/playwright-results/search-${test.info().project.name}.png`, fullPage: true })
})

test('来源中的 HTML 与图片不能执行，设置和任务页面可访问', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '记录内容', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '随手记', exact: true }).click()
  await dialog.getByLabel('标题').fill('Rerank HTML 渲染边界测试')
  await dialog.getByLabel('此刻的想法').fill('<img src=x onerror="window.__renderProbe=1">\n![外部图片](https://remote-image.invalid/image.png)\nRerank 原文。')
  await dialog.getByRole('button', { name: '保存到知识库' }).click()
  await expect(page.getByRole('heading', { name: '内容概览' })).toBeVisible({ timeout: 15000 })
  await expect(page.locator('.analysis-point')).toContainText('Rerank 原文')
  expect(await page.locator('.analysis-point img').count()).toBe(0)
  expect(await page.evaluate(() => '__renderProbe' in window)).toBeFalsy()
  await page.getByRole('link', { name: '设置与用量', exact: true }).click()
  await expect(page.getByRole('heading', { name: '模型用量', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '整理进度', exact: true }).click()
  await expect(page.getByRole('table')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
