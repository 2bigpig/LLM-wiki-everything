import { expect, test } from '@playwright/test'

test('统一输入混合素材、再次收藏与图谱时间线', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: '记录内容', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('button', { name: '链接收藏', exact: true })).toHaveCount(0)
  await dialog.getByLabel('内容', { exact: true }).fill('Rerank 这次准备用于项目。\nhttps://example.com/unified\nhttps://youtu.be/revisit-demo\nhttps://example.com/retry-fixture-' + testInfo.project.name)
  await expect(dialog.locator('.capture-links label')).toHaveCount(3)
  await dialog.getByLabel('选择上传文件').setInputFiles([
    { name: 'capture.txt', mimeType: 'text/plain', buffer: Buffer.from('Rerank 附件中的原始记录。') },
    { name: 'remove.txt', mimeType: 'text/plain', buffer: Buffer.from('remove me') },
  ])
  await dialog.getByRole('button', { name: '移除附件 remove.txt', exact: true }).click()
  await dialog.locator('form').evaluate(element => {
    const transfer = new DataTransfer()
    transfer.items.add(new File(['Rerank 拖入的原始文本。'], 'drag.txt', { type: 'text/plain' }))
    element.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }))
  })
  await expect(dialog.locator('.capture-files')).toContainText('drag.txt')
  // 合成真实 ClipboardEvent，验证截图文件走同一个输入区，而非专用图片入口。
  await dialog.getByLabel('内容', { exact: true }).evaluate(element => {
    const bytes = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAIAAAD91JpzAAAAE0lEQVR4nGP8//8/AwMDEwMYAAAkBgMBXaJOiAAAAABJRU5ErkJggg=='), char => char.charCodeAt(0))
    const transfer = new DataTransfer()
    transfer.items.add(new File([bytes], 'clipboard.png', { type: 'image/png' }))
    element.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData: transfer }))
  })
  await expect(dialog.locator('.capture-files')).toContainText('clipboard.png')
  await dialog.getByText('更多选项', { exact: true }).click()
  const firstTitle = 'Rerank 混合素材 ' + testInfo.project.name
  await dialog.getByLabel('标题').fill(firstTitle)
  await dialog.getByRole('button', { name: '保存到知识库' }).click()
  await expect(page.getByRole('heading', { name: firstTitle, exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '内容概览', exact: true })).toBeVisible({ timeout: 15000 })
  await expect(page.locator('.source-inputs')).toContainText('已读取')
  await expect(page.locator('.source-input').filter({ hasText: 'clipboard.png' })).toContainText('已读取')
  const failed = page.locator('.source-input').filter({ hasText: 'retry-fixture-' + testInfo.project.name })
  await expect(failed).toContainText('读取失败')
  await failed.getByRole('button', { name: '重试此来源', exact: true }).click()
  await expect(failed).toContainText('已读取', { timeout: 15000 })
  await page.getByRole('button', { name: '记录内容', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('内容', { exact: true }).fill('这次有了新的想法。 https://www.youtube.com/watch?v=revisit-demo')
  await dialog.getByRole('button', { name: '保存到知识库' }).click()
  await expect(page.locator('.capture-history')).toContainText(firstTitle)
  const video = page.locator('.source-input').filter({ hasText: 'youtube.com/watch?v=revisit-demo' })
  await video.getByRole('link', { name: '时间线', exact: true }).click()
  await expect(page.getByRole('heading', { name: '知识图谱', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关系列表', exact: true }).click()
  await page.locator('.graph-node-button').filter({ hasText: 'youtu.be/revisit-demo' }).first().click()
  await expect(page.locator('.capture-timeline')).toContainText(firstTitle)
  await expect(page.locator('.capture-timeline li')).not.toHaveCount(0)
  await page.getByRole('button', { name: '图形', exact: true }).click()
  await expect(page.locator('.graph-canvas canvas').first()).toBeVisible()
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: `../data/playwright-results/graph-${testInfo.project.name}.png`, fullPage: true })
})

test('站内回顾可暂停、恢复并反馈，不要求配置模型', async ({ page }) => {
  await page.goto('/reviews')
  await expect(page.getByRole('heading', { name: '发现与回顾', exact: true })).toBeVisible()
  await expect(page.locator('.review-card').first()).toBeVisible()
  await page.getByRole('button', { name: /暂停.*7.*天/ }).click()
  await expect(page.getByText(/已暂停至/)).toBeVisible()
  await expect(page.locator('.review-card')).toHaveCount(0)
  await page.getByRole('button', { name: '恢复回顾', exact: true }).click()
  await expect(page.locator('.review-card').first()).toBeVisible()
  const count = await page.locator('.review-card').count()
  expect(count).toBeGreaterThan(0)
  await page.locator('.review-card').first().getByRole('button', { name: '暂不需要', exact: true }).click()
  await expect(page.locator('.review-card')).toHaveCount(count - 1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
