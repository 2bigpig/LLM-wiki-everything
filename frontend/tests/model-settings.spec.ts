import { test, expect } from '@playwright/test'

test('模型连接、JSON 测试、阶段分配和停用在桌面与手机可用', async ({ page }, testInfo) => {
  await page.goto('/settings')
  await page.locator('.advanced-settings > summary').click()
  await expect(page.getByRole('heading', { name: '向量索引', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '准备空间', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '添加连接', exact: true }).click()
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '添加连接', exact: true }) })
  const name = '浏览器模型连接-' + Date.now()
  await dialog.getByLabel('连接名称').fill(name)
  await dialog.getByLabel('服务地址').fill('http://127.0.0.1:9991/v1')
  await dialog.getByLabel('API Key').fill('browser-only-key')
  await dialog.getByRole('button', { name: '显示密钥', exact: true }).click()
  await expect(dialog.getByLabel('API Key')).toHaveAttribute('type', 'text')
  await dialog.getByRole('button', { name: '隐藏密钥', exact: true }).click()
  await expect(dialog.getByLabel('API Key')).toHaveAttribute('type', 'password')
  await dialog.getByRole('button', { name: '保存连接', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const connection = page.locator('.model-row').filter({ has: page.locator('.model-row-title strong', { hasText: name }) })
  await expect(connection).toContainText('密钥已配置')
  await expect(connection).not.toContainText('browser-only-key')
  await page.getByRole('button', { name: '添加模型', exact: true }).click()
  const model = page.getByRole('dialog', { name: '模型配置', exact: true })
  await model.getByRole('combobox', { name: '模型连接', exact: true }).selectOption({ label: name })
  await model.getByLabel('名称', { exact: true }).fill(name + '-LLM')
  await model.getByLabel('模型 ID', { exact: true }).fill('glm-browser-test')
  await expect(model.getByLabel('类型', { exact: true })).toHaveCount(0)
  await expect(model.getByRole('option', { name: '本地 BGE-M3', exact: true })).toHaveCount(0)
  await model.getByRole('button', { name: '保存模型', exact: true }).click()
  await expect(model).not.toBeVisible()
  await connection.getByRole('button', { name: '测试 JSON', exact: true }).click()
  await expect(connection).toContainText('最近测试：通过')
  await page.getByLabel('默认模型', { exact: true }).selectOption({ label: name + '-LLM · glm-browser-test' })
  await page.getByRole('button', { name: '保存用途分配', exact: true }).click()
  await page.reload()
  await page.locator('.advanced-settings > summary').click()
  await expect(page.getByLabel('默认模型', { exact: true }).locator('option:checked')).toContainText(name)
  await connection.getByRole('button', { name: '停用', exact: true }).click()
  await expect(connection).toContainText('已停用')
  expect(await page.locator('body').evaluate(e => e.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../data/model-settings-' + testInfo.project.name + '.png', fullPage: true })
})
